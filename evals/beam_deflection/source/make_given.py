"""Makes the given file for the beam_deflection eval: the support block the beam rests on.

Run from the repo root with the cad-agent Python:

    python evals/beam_deflection/source/make_given.py

It writes a STEP file and its source note into evals/beam_deflection/given/bought/, the same pair `cad bought
add-step` leaves in a project (it calls the same function), and adds the keys of the bought-part contract
(bought.py) that the rules of step 6 read: the block's material, and its mass with where the mass came from. The
STEP is written with cad_agent.export.write_step, so every run writes the same bytes; the committed file is the
artefact, and this script says how it was made.

The block is this task's fixture, not a vendor's part: a plain 40 mm cube of mild steel. Its mass is declared so that
the centre-of-mass rule, which wants every body's mass once any bought body states one (the beam may be a library
extrusion that does), can judge the assembly. The same file is placed twice, as `support_left` and `support_right`.
"""
from __future__ import annotations

import json
import shutil
import sys
import tempfile
from pathlib import Path

from build123d import Box, Pos

from cad_agent import state
from cad_agent.bought import register_step
from cad_agent.export import write_step

OUT = Path(__file__).resolve().parent.parent / "given" / "bought"

SIZE = 40.0                # the block is a cube, mm
STEEL_G_CM3 = 7.85         # what `cad tables density` gives steel

SOURCE = (
    "Task-given support block for the beam_deflection eval: a 40 x 40 x 40 mm cube of mild steel, a plain box with "
    "no holes. The same file stands at each end of the beam. Origin at the centre of the block. "
    "Generated by evals/beam_deflection/source/make_given.py"
)
MASS_G = round(SIZE ** 3 / 1000.0 * STEEL_G_CM3, 1)
MASS_SOURCE = (
    f"this task's own number: 40 x 40 x 40 mm is 64 cm3, at steel's {STEEL_G_CM3} g/cm3 from `cad tables density` "
    f"({MASS_G} g)"
)


def support():
    return Box(SIZE, SIZE, SIZE)


def main() -> int:
    slug = "make_given"
    with tempfile.TemporaryDirectory() as tmp:
        state.ROOT = Path(tmp)
        state.project_dir(slug, create=True)
        step = Path(tmp) / "support.step"
        write_step(Pos(0, 0, 0) * support(), step)
        dest = register_step(slug, "support", str(step), SOURCE, None)
        sidecar = dest.with_suffix(".json")
        note = json.loads(sidecar.read_text())
        note.update({"material": "steel", "mass_g": MASS_G, "mass_source": MASS_SOURCE})
        sidecar.write_text(json.dumps(note, indent=1))
        OUT.mkdir(parents=True, exist_ok=True)
        for p in sorted((Path(tmp) / slug / "bought").iterdir()):
            shutil.copy(p, OUT / p.name)
            print(f"wrote {OUT / p.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
