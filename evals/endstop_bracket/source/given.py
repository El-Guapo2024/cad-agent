"""Generator for endstop_bracket's given bodies: a 2040 extrusion, an Omron SS-5GL and a flag.

Run once from anywhere to rewrite the three STEPs and their sidecars in
given/bought/:

    python evals/endstop_bracket/source/given.py

The files are registered the way `cad bought add-step` does it (the STEP plus a
sidecar naming where the numbers came from), so the provenance gate passes and
nothing in the task is a remembered dimension.

The switch is drawn in the frame of the datasheet's side view: x along the 19.8 mm
body, z up toward the lever, y through the 6.4 mm thickness. The origin is the
midpoint of the two mounting holes, whose axes run along y at z = 0, so the holes
sit at x = -4.75 and +4.75. The lever is drawn flat at the operating position.

Where each number comes from (Omron catalogue B032-E1-14, "SS Subminiature Basic
Switch", hinge lever SS-5GL, page 5 drawing and table; terminals on page 4):

  body             19.8 long, 6.4 thick, 9.5 tall (10.2 over the lever's hinge
                   end); the hole axes are 2.5 above the bottom face
  mounting holes   2 x 2.35 dia, 9.5 apart, the first 5.1 from the left end;
                   the mating panel takes 2.4 dia holes or M2.3 screws (page 4)
  lever            stainless, t = 0.3, hinged near the left end, tip 14.5 from
                   the first hole; operating position OP = 8.8 +/- 0.8 above the
                   hole axes (free position FP = 13.6 max, overtravel OT = 1.2 min)
  terminals        three solder tabs 0.5 thick, 1.6 / 8.8 / 7.3 apart, 6.4 below
                   the hole axes

The raised end of the body (the step near the hinge) and the width of the tabs
and lever are read off the drawing to about 0.3 mm; none of them is graded.

The extrusion is the envelope of a 2040 profile (20 x 40 mm, `cad tables`) with the
slots left out, which is what cad_agent.parts.extrusion_blank draws. The flag is
a plain tab defined by the task, not a catalogue part.
"""
from __future__ import annotations

import shutil
import sys
import tempfile
from pathlib import Path

from build123d import Box, Cylinder, Pos, Rot, export_step

from cad_agent.parts import extrusion_blank

HERE = Path(__file__).resolve().parent
GIVEN = HERE.parent / "given" / "bought"

LENGTH_EXTRUSION = 200.0
FLAG = (6.0, 12.0, 14.0)

# Omron SS-5GL, mm, in the frame described above.
X_LEFT, X_RIGHT = -9.85, 9.95          # 5.1 left of the first hole, 19.8 long
HOLE_X = 4.75
THICK = 6.4
Z_BOTTOM, Z_TOP, Z_RAISED = -2.5, 7.0, 7.7
X_STEP = -0.55                         # the raised hinge end runs from the left end to here
HOLE_D = 2.35
LEVER_X0, LEVER_X1 = -6.75, 9.75       # hinge 3.1 from the left end, tip 14.5 from the first hole
LEVER_W, LEVER_T, LEVER_TOP = 3.6, 0.3, 8.8
TABS_X = (-8.25, 0.55, 7.85)           # left faces of the three terminals
TAB_T, TAB_W, TAB_BOTTOM = 0.5, 2.5, -6.4

EXTRUSION_SOURCE = (
    "generic 2040 T-slot profile envelope, 20 x 40 x 200 mm (`cad tables`: 2040 is 20 x 40); "
    "slots and centre bores not modelled, as cad_agent.parts.extrusion_blank. "
    "Generated by evals/endstop_bracket/source/given.py")
SWITCH_SOURCE = (
    "Omron SS subminiature basic switch catalogue B032-E1-14, hinge lever SS-5GL: page 5 drawing "
    "(body 19.8 x 6.4 x 9.5/10.2, 2 x 2.35 dia holes 9.5 apart, lever tip 14.5 from hole 1, "
    "OP 8.8) and page 4 terminals. Lever drawn at the operating position. "
    "Generated by evals/endstop_bracket/source/given.py")
FLAG_SOURCE = (
    "eval fixture, not a catalogue part: a 6 x 12 x 14 mm tab on the carriage, defined by the "
    "task. Generated by evals/endstop_bracket/source/given.py")


def extrusion():
    return extrusion_blank("2040", LENGTH_EXTRUSION, axis="z")


def flag():
    return Box(*FLAG)


def switch():
    """The SS-5GL: body, hinge end, flat lever at OP, three solder tabs, two mounting holes."""
    def block(x0, x1, y0, y1, z0, z1):
        return Pos((x0 + x1) / 2.0, (y0 + y1) / 2.0, (z0 + z1) / 2.0) * Box(x1 - x0, y1 - y0, z1 - z0)

    half = THICK / 2.0
    body = block(X_LEFT, X_RIGHT, -half, half, Z_BOTTOM, Z_TOP)
    body += block(X_LEFT, X_STEP, -half, half, Z_TOP, Z_RAISED)
    # The lever: a hook down to the raised end, then a flat strip at the operating position.
    lw = LEVER_W / 2.0
    body += block(LEVER_X0, LEVER_X0 + LEVER_T, -lw, lw, Z_RAISED, LEVER_TOP - LEVER_T)
    body += block(LEVER_X0, LEVER_X1, -lw, lw, LEVER_TOP - LEVER_T, LEVER_TOP)
    for x in TABS_X:
        body += block(x, x + TAB_T, -TAB_W / 2.0, TAB_W / 2.0, TAB_BOTTOM, Z_BOTTOM)
    for x in (-HOLE_X, HOLE_X):
        body -= Pos(x, 0, 0) * Rot(90, 0, 0) * Cylinder(HOLE_D / 2.0, THICK + 2.0)
    return body


def register(name: str, solid, source: str, vendor: str) -> None:
    """Write the STEP and its sidecar into given/bought, as `cad bought add-step` would."""
    from cad_agent import state
    from cad_agent.bought import register_step
    with tempfile.TemporaryDirectory() as tmp:
        state.ROOT = Path(tmp)
        state.project_dir("scratch", create=True)
        step = Path(tmp) / f"{name}.step"
        export_step(solid, str(step))
        register_step("scratch", name, str(step), source, vendor)
        GIVEN.mkdir(parents=True, exist_ok=True)
        for ext in (".step", ".json"):
            shutil.copy(Path(tmp) / "scratch" / "bought" / f"{name}{ext}", GIVEN / f"{name}{ext}")


def main() -> int:
    register("extrusion_2040", extrusion(), EXTRUSION_SOURCE, "generic 2040 T-slot")
    register("omron_ss5gl", switch(), SWITCH_SOURCE, "Omron")
    register("carriage_flag", flag(), FLAG_SOURCE, "cad-agent eval fixture")
    print(f"wrote {GIVEN}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
