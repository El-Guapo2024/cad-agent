"""Makes the given files for the dock_material eval: the 250 C hot plate and the steel base plate under it.

Run from the repo root with the cad-agent Python:

    python evals/dock_material/source/make_given.py

It writes a STEP file and a source note for each body into evals/dock_material/given/bought/, the same pair `cad
bought add-step` leaves in a project (it calls the same function), and adds to the base plate's note the keys of
the bought-part contract (bought.py) that the heat rule reads: its material, and the highest temperature it may sit
at with where that number came from. The base plate lies under the hot plate, so it is inside the 15 mm zone of
the task's `[[heat]]`: with no declared rating the rule would say UNCHECKED for it. The STEPs are written with
cad_agent.export.write_step, so every run writes the same bytes; the committed STEPs are the artefacts, and this
script says how they were made.

Every number is a dimension of the brief; the tap drill comes from cad_agent.parts, so the interface rule and these
files cannot drift apart.
"""
from __future__ import annotations

import json
import shutil
import sys
import tempfile
from pathlib import Path

from build123d import Box, Cylinder, Pos

from cad_agent import state
from cad_agent.bought import register_step
from cad_agent.export import write_step
from cad_agent.parts import TAP_DRILL

OUT = Path(__file__).resolve().parent.parent / "given" / "bought"

PLATE_X, PLATE_Y, PLATE_T = 80.0, 60.0, 10.0       # the hot plate: the thinnest HAP250 plate Hillesheim lists
BASE_X, BASE_Y, BASE_T = 140.0, 120.0, 6.0         # the base plate
HOLE_X, HOLE_Y = 40.0, 40.0                        # the base's four M4 holes are at (+-40, +-40)

HOT_PLATE_SOURCE = (
    "Hillesheim GmbH HAP250 aluminium electric heating plate, "
    "https://www.hillesheim-gmbh.com/en/products/aluminium-electric_heating_plate.php "
    "(read 2026-10-04): AlMg3 (EN AW-5754), 10 to 20 mm thick, 250 C maximum operating "
    "temperature, bore holes and bolt threads made to order. The vendor publishes no drawing: "
    "the 80 x 60 x 10 mm outline is this task's order, and the plate has no holes. Modelled as a "
    "plain plate; the heater element is not modelled. "
    "Generated by evals/dock_material/source/make_given.py"
)
BASE_PLATE_SOURCE = (
    "Task-given base plate for the dock_material eval: 140 x 120 x 6 mm mild steel, four M4 tapped "
    "holes at (+-40, +-40), modelled at the 3.3 mm tap drill (cad tables taps) and through. "
    "Origin at the centre of the top face. "
    "Generated by evals/dock_material/source/make_given.py"
)
STEEL_URL = "https://www.makeitfrom.com/material-properties/ASTM-A36-SS400-S275-Structural-Carbon-Steel"
BASE_PLATE_RATING = (
    400.0,
    f"{STEEL_URL}: MakeItFrom.com, ASTM A36 (SS400, S275) structural carbon steel, Thermal Properties: "
    "Maximum Temperature: Mechanical 400 °C (750 °F), read 2026-10-12; the number `cad tables materials` gives steel",
)


def hot_plate():
    """Underside at z = 0, centred on x = y = 0, +z up: placed as it is, it stands on the base plate."""
    return Pos(0, 0, PLATE_T / 2.0) * Box(PLATE_X, PLATE_Y, PLATE_T)


def base_plate():
    """Top face at z = 0, centred on x = y = 0, so the plate spans z -6 to 0. The four tapped holes go through."""
    body = Pos(0, 0, -BASE_T / 2.0) * Box(BASE_X, BASE_Y, BASE_T)
    d = TAP_DRILL["M4"]
    for sx in (-1, 1):
        for sy in (-1, 1):
            body -= Pos(sx * HOLE_X, sy * HOLE_Y, -BASE_T / 2.0) * Cylinder(d / 2.0, BASE_T + 2.0)
    return body


def main() -> int:
    slug = "make_given"
    with tempfile.TemporaryDirectory() as tmp:
        state.ROOT = Path(tmp)
        state.project_dir(slug, create=True)
        for name, solid, source, vendor, declares in (
                ("hot_plate", hot_plate(), HOT_PLATE_SOURCE, "Hillesheim GmbH", {}),
                ("base_plate", base_plate(), BASE_PLATE_SOURCE, None,
                 {"material": "steel", "max_temp_c": BASE_PLATE_RATING[0], "max_temp_source": BASE_PLATE_RATING[1]})):
            step = Path(tmp) / f"{name}.step"
            write_step(solid, step)
            sidecar = register_step(slug, name, str(step), source, vendor).with_suffix(".json")
            if declares:
                note = json.loads(sidecar.read_text())
                note.update(declares)
                sidecar.write_text(json.dumps(note, indent=1))
        OUT.mkdir(parents=True, exist_ok=True)
        for p in sorted((Path(tmp) / slug / "bought").iterdir()):
            shutil.copy(p, OUT / p.name)
            print(f"wrote {OUT / p.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
