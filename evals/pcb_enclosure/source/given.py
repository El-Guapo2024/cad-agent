"""Generator for pcb_enclosure's given bodies: an Arduino UNO R3 and its USB-B plug.

Run once from anywhere to rewrite given/bought/arduino_uno_r3.{step,json} and
usb_b_plug.{step,json}:

    python evals/pcb_enclosure/source/given.py

The files are registered the way `cad bought add-step` does it (the STEP plus
a sidecar naming where the numbers came from), so the project's provenance gate
passes and nothing in the task is a remembered dimension.

Both bodies share one frame, the board's: the origin is the centre of the board
outline, z = 0 is the underside of the PCB, x runs along the long edge with the
USB socket at -x, y across the short edge. The plug is already in its plugged-in
position in that frame, so one transform places them both.

Where each number comes from:

  Board outline, 4 x 3.20 mm mounting holes
      Arduino UNO R3 datasheet A000066, section 5.4 (page 12). The drawing
      dimensions the upper-left hole at 15.24 mm from the left edge and the
      right pair at 66.04 mm. It does not dimension the lower-left hole's x, but
      draws it about 1.3 mm nearer the edge: 13.97 mm (550 mil), the usual R3
      pattern. The right edge steps out 2.54 mm between two 45 degree chamfers,
      read off the same drawing to about 0.2 mm.
  USB-B socket   16.5 x 12.2 x 10.8 mm
      Same Sky UJ2-BH-2-TH, a through-hole horizontal type B receptacle (the
      size is from its product page). Its front sits 6.4 mm past the board edge
      and its axis is 15.24 mm from the top edge, both read off the drawing above.
  DC jack        14.4 x 9.0 x 11.0 mm
      Same Sky PJ-002A (size from its product page), 7.62 mm from the bottom
      edge. The drawing puts its front 1.6 mm past the board edge; it is moved
      out to 2.1 mm so its rear end stays clear of the lower-left hole.
  Headers        2.54 mm female strips, 8.5 mm tall
      A typical stackable header height, and positions from the usual UNO layout
      (10-pin and 8-pin on top with the odd 0.16 in gap between them, 8-pin and
      6-pin along the bottom). Neither is on the Arduino drawing, so treat them as
      approximate. They are lower than the sockets and inside the board's
      footprint, so no graded number depends on them.
  USB-B plug     26.7 x 11.4 x 10.5 mm
      W+P Products series 826 (USB 2.0 cable assemblies), "Housing
      Dimensions", USB B male. Modelled as that one block with its front face
      on the socket's front face: the metal shell that goes inside the socket
      is not drawn, and the cable leaves along the same axis, so the block
      doubles as the path the plug takes in and out through a wall.
"""
from __future__ import annotations

import shutil
import sys
import tempfile
from pathlib import Path

from build123d import Box, Cylinder, Polygon, Pos, export_step, extrude, fillet

HERE = Path(__file__).resolve().parent
GIVEN = HERE.parent / "given" / "bought"

# Board outline, counter-clockwise (a clockwise one extrudes downward), centred on the
# 68.58 x 53.34 mm rectangle.
PCB_T = 1.6
OUTLINE = [(-34.29, -26.67), (31.75, -26.67), (31.75, -24.13), (34.29, -21.59),
           (34.29, 11.43), (31.75, 13.97), (31.75, 25.40), (30.48, 26.67),
           (-34.29, 26.67)]
HOLE_D = 3.20
HOLES = [(-19.05, 24.13), (-20.32, -24.13), (31.75, 8.89), (31.75, -19.05)]

# Connector blocks, all standing on the top face of the PCB.
USB = {"front_x": -40.69, "len": 16.5, "w": 12.2, "h": 10.8, "y": 11.43}
JACK = {"front_x": -36.39, "len": 14.4, "w": 9.0, "h": 11.0, "y": -19.05}
HEADER_H, HEADER_W = 8.5, 2.54
# (first pin x, pin count, row y) in board coordinates; pins are 2.54 apart.
HEADERS = [(-15.49, 10, 24.13), (11.43, 8, 24.13),
           (-8.89, 8, -24.13), (13.97, 6, -24.13)]

PLUG = {"len": 26.7, "w": 11.4, "h": 10.5, "round": 1.0}

UNO_SOURCE = (
    "Arduino UNO R3 datasheet A000066 section 5.4, page 12 (board outline and 4 x 3.20 mm "
    "holes); USB-B socket 16.5 x 12.2 x 10.8 mm from Same Sky UJ2-BH-2-TH, DC jack "
    "14.4 x 9 x 11 mm from Same Sky PJ-002A; 8.5 mm headers typical, positions approximate. "
    "Generated by evals/pcb_enclosure/source/given.py")
PLUG_SOURCE = (
    "W+P Products series 826 USB 2.0 cable assemblies datasheet, Housing Dimensions table, "
    "USB B male 26.7 x 11.4 x 10.5 mm, one block seated on the socket face. "
    "Generated by evals/pcb_enclosure/source/given.py")


def uno():
    """The board: FR4 outline with its holes, and the tall parts as blocks."""
    board = extrude(Polygon(*OUTLINE, align=None), amount=PCB_T)
    for x, y in HOLES:
        board -= Pos(x, y, PCB_T / 2.0) * Cylinder(HOLE_D / 2.0, PCB_T + 2.0)
    top = PCB_T
    for c in (USB, JACK):
        board += Pos(c["front_x"] + c["len"] / 2.0, c["y"], top + c["h"] / 2.0) * Box(
            c["len"], c["w"], c["h"])
    for x0, n, y in HEADERS:
        length = n * HEADER_W
        board += Pos(x0 - HEADER_W / 2.0 + length / 2.0, y, top + HEADER_H / 2.0) * Box(
            length, HEADER_W, HEADER_H)
    return board


def usb_plug():
    """The plug's housing, plugged into the socket: front face on the socket's."""
    block = Box(PLUG["len"], PLUG["w"], PLUG["h"])
    block = fillet(block.edges(), PLUG["round"])
    return Pos(USB["front_x"] - PLUG["len"] / 2.0, USB["y"], PCB_T + USB["h"] / 2.0) * block


def register(name: str, solid, source: str, vendor: str) -> None:
    """Write the STEP and its sidecar into given/bought, as `cad bought add-step` would."""
    from cad_agent import state
    from cad_agent.bought import register_step
    with tempfile.TemporaryDirectory() as tmp:
        state.ROOT = Path(tmp)
        state.project_dir("scratch", create=True)
        step = Path(tmp) / f"{name}.step"
        export_step(solid, str(step))
        register_step("scratch", name, str(step), source, vendor)
        GIVEN.mkdir(parents=True, exist_ok=True)
        for ext in (".step", ".json"):
            shutil.copy(Path(tmp) / "scratch" / "bought" / f"{name}{ext}", GIVEN / f"{name}{ext}")


def main() -> int:
    register("arduino_uno_r3", uno(), UNO_SOURCE, "Arduino S.r.l. (outline), Same Sky (connectors)")
    register("usb_b_plug", usb_plug(), PLUG_SOURCE, "W+P Products")
    print(f"wrote {GIVEN}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
