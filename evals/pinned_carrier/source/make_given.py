"""Makes the given files for the pinned_carrier eval: the base plate, a dowel pin and the screw.

Run from the repo root with the cad-agent Python:

    python evals/pinned_carrier/source/make_given.py

It writes a STEP file and a source note for each body into
evals/pinned_carrier/given/bought/, the same pair `cad bought add-step` leaves in a
project (it calls the same function). The STEPs are written with
cad_agent.export.write_step, so every run writes the same bytes; the committed STEPs
are the artefacts, and this script says how they were made.

The dowel pin and the screw are modelled at their nominal sizes from the standards'
tables; the hole sizes come from cad_agent.parts, so the interface rule and these
files cannot drift apart.
"""
from __future__ import annotations

import shutil
import sys
import tempfile
from pathlib import Path

from build123d import Box, Cylinder, GeomType, Pos, RegularPolygon, chamfer, extrude

from cad_agent import state
from cad_agent.bought import register_step
from cad_agent.export import write_step
from cad_agent.parts import CLEARANCE_HOLE

OUT = Path(__file__).resolve().parent.parent / "given" / "bought"

BASE_X, BASE_Y, BASE_T = 100.0, 60.0, 10.0
PIN_X = 25.0           # the two pins stand at (+-25, 0)
PIN_D, PIN_L = 4.0, 16.0
PIN_IN = 6.0           # pressed in 6 mm, so 10 mm stand above the base top
PIN_C = 0.63           # end chamfer, ISO 8734 table for d = 4
HEAD_D, HEAD_K = 7.0, 4.0        # ISO 4762 M4: dk 7.0, k 4.0
SOCKET_S, SOCKET_T = 3.0, 2.0    # hex socket 3 mm across flats; at least 2 mm deep
SCREW_L = 10.0         # M4 x 10: the tip ends flush with the base underside

PIN_SOURCE = (
    "ISO 8734:1997 parallel pin of hardened steel (dowel pin), 4 m6 x 16: d 4.004 to 4.012 mm "
    "(modelled at the nominal 4.0 mm), chamfer c 0.63 mm at both ends (45 degrees assumed). "
    "Table read at https://www.globalfastener.com/standards/detail_260.html and "
    "https://engineersedge.com/hardware/iso_metric_dowel_pins_13805.htm. "
    "Origin on the axis at the bottom end, +z along the pin. "
    "Generated by evals/pinned_carrier/source/make_given.py"
)
SCREW_SOURCE = (
    "ISO 4762 hexagon socket head cap screw M4 x 10: head 7.0 mm across x 4.0 mm high, hex socket "
    "3.0 mm across flats x 2 mm deep, plain 4.0 mm shank, thread not modelled. Table read at "
    "https://engineersedge.com/iso_socket_head_screw.htm. Origin on the axis at the head's "
    "bearing face, the shank pointing -z. "
    "Generated by evals/pinned_carrier/source/make_given.py"
)
BASE_SOURCE = (
    "Task-given base plate for the pinned_carrier eval: 100 x 60 x 10 mm steel. Two 4.0 mm blind "
    "holes 6 mm deep at (+-25, 0) for the pressed-in dowel pins (a 4 H7 hole, modelled at the "
    "pin's nominal size), and one 4.5 mm (M4 clearance, cad tables) through hole at (0, 0) for the "
    "clamp screw. Origin at the centre of the top face. "
    "Generated by evals/pinned_carrier/source/make_given.py"
)


def base_plate():
    """Top face at z = 0, centred on x = y = 0, so the plate spans z -10 to 0."""
    body = Pos(0, 0, -BASE_T / 2.0) * Box(BASE_X, BASE_Y, BASE_T)
    for sx in (-1, 1):
        body -= Pos(sx * PIN_X, 0, -PIN_IN / 2.0) * Cylinder(PIN_D / 2.0, PIN_IN)
    body -= Pos(0, 0, -BASE_T / 2.0) * Cylinder(CLEARANCE_HOLE["M4"] / 2.0, BASE_T + 2.0)
    return body


def dowel_pin():
    """Bottom end on z = 0, standing up the +z axis."""
    pin = Pos(0, 0, PIN_L / 2.0) * Cylinder(PIN_D / 2.0, PIN_L)
    return chamfer(pin.edges().filter_by(GeomType.CIRCLE), PIN_C)


def clamp_screw():
    """Head bearing face on z = 0, head above it, shank down to z = -10."""
    head = Pos(0, 0, HEAD_K / 2.0) * Cylinder(HEAD_D / 2.0, HEAD_K)
    shank = Pos(0, 0, -SCREW_L / 2.0) * Cylinder(PIN_D / 2.0, SCREW_L)
    circumradius = SOCKET_S / 2.0 / 0.8660254037844386        # across flats -> across corners
    socket = Pos(0, 0, HEAD_K - SOCKET_T) * extrude(RegularPolygon(circumradius, 6), SOCKET_T)
    return head + shank - socket


def main() -> int:
    slug = "make_given"
    with tempfile.TemporaryDirectory() as tmp:
        state.ROOT = Path(tmp)
        state.project_dir(slug, create=True)
        for name, solid, source, vendor in (
                ("base_plate", base_plate(), BASE_SOURCE, None),
                ("dowel_pin", dowel_pin(), PIN_SOURCE, None),
                ("clamp_screw", clamp_screw(), SCREW_SOURCE, None)):
            step = Path(tmp) / f"{name}.step"
            write_step(solid, step)
            register_step(slug, name, str(step), source, vendor)
        OUT.mkdir(parents=True, exist_ok=True)
        for p in sorted((Path(tmp) / slug / "bought").iterdir()):
            shutil.copy(p, OUT / p.name)
            print(f"wrote {OUT / p.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
