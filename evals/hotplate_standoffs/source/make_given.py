"""Makes the given files for the hotplate_standoffs eval: the hot plate and the base plate.

Run from the repo root with the cad-agent Python:

    python evals/hotplate_standoffs/source/make_given.py

It writes a STEP file and a source note for each body into
evals/hotplate_standoffs/given/bought/, the same pair `cad bought add-step`
leaves in a project (it calls the same function). STEP files carry a timestamp,
so they never come out byte for byte the same twice: the committed STEPs are the
artefacts, and this script says how they were made.

Every number is a dimension of the brief; the hole sizes come from
cad_agent.parts, so the interface rule and these files cannot drift apart.
"""
from __future__ import annotations

import shutil
import sys
import tempfile
from pathlib import Path

from build123d import Box, Cylinder, Pos, export_step

from cad_agent import state
from cad_agent.bought import register_step
from cad_agent.parts import CLEARANCE_HOLE, TAP_DRILL

OUT = Path(__file__).resolve().parent.parent / "given" / "bought"

PLATE = 100.0          # hot plate outline, square
PLATE_T = 10.0         # the thinnest HAP250 plate Hillesheim lists
TAP_DEPTH = 7.0        # drilled depth of each blind M3 hole, leaving a 3 mm skin on top
BASE = 160.0           # base plate outline, square
BASE_T = 6.0
HOLE = 43.0            # hole centres at +-43 mm: 7 mm in from each edge of the hot plate

HOT_PLATE_SOURCE = (
    "Hillesheim GmbH HAP250 aluminium electric heating plate, "
    "https://www.hillesheim-gmbh.com/en/products/aluminium-electric_heating_plate.php "
    "(read 2026-10-04): AlMg3 (EN AW-5754), 10 to 20 mm thick, 250 C maximum operating "
    "temperature, bore holes and bolt threads made to order. The vendor publishes no drawing: "
    "the 100 x 100 x 10 mm outline and the four M3 holes 7 mm from the edges are this task's "
    "order. Modelled as a plain plate; the heater element is not modelled. "
    "Generated by evals/hotplate_standoffs/source/make_given.py"
)
BASE_PLATE_SOURCE = (
    "Task-given base plate for the hotplate_standoffs eval: 160 x 160 x 6 mm aluminium, "
    "four 3.4 mm (M3 clearance, cad tables) through holes at the hot plate's hole pattern. "
    "Generated by evals/hotplate_standoffs/source/make_given.py"
)


def hot_plate():
    """Underside at z = 0, centred on x = y = 0. Blind tapped holes open on the underside,
    so the top face, the one that carries the board, stays unbroken."""
    body = Pos(0, 0, PLATE_T / 2.0) * Box(PLATE, PLATE, PLATE_T)
    d = TAP_DRILL["M3"]
    for sx in (-1, 1):
        for sy in (-1, 1):
            body -= Pos(sx * HOLE, sy * HOLE, TAP_DEPTH / 2.0) * Cylinder(d / 2.0, TAP_DEPTH)
    return body


def base_plate():
    """Top face at z = 0, centred on x = y = 0, so the plate spans z -6 to 0 and the
    screws come up from underneath."""
    body = Pos(0, 0, -BASE_T / 2.0) * Box(BASE, BASE, BASE_T)
    d = CLEARANCE_HOLE["M3"]
    for sx in (-1, 1):
        for sy in (-1, 1):
            body -= Pos(sx * HOLE, sy * HOLE, -BASE_T / 2.0) * Cylinder(d / 2.0, BASE_T + 2.0)
    return body


def main() -> int:
    slug = "make_given"
    with tempfile.TemporaryDirectory() as tmp:
        state.ROOT = Path(tmp)
        state.project_dir(slug, create=True)
        for name, solid, source, vendor in (
                ("hot_plate", hot_plate(), HOT_PLATE_SOURCE, "Hillesheim GmbH"),
                ("base_plate", base_plate(), BASE_PLATE_SOURCE, None)):
            step = Path(tmp) / f"{name}.step"
            export_step(solid, str(step))
            register_step(slug, name, str(step), source, vendor)
        OUT.mkdir(parents=True, exist_ok=True)
        for p in sorted((Path(tmp) / slug / "bought").iterdir()):
            shutil.copy(p, OUT / p.name)
            print(f"wrote {OUT / p.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
