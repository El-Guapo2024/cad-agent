"""The holes tests/test_feature_hole.py builds with cad_agent.feature and make.py builds in FreeCAD.

STATES: the properties chosen for a Hole on a 40 x 20 x 10 plate; make.py sets them in feature_hole.ORDER on a new
FreeCAD Hole and records every property's value, its editor mode and each enumeration's list, which HoleState must give
too. CASES: bodies with holes, which must give FreeCAD's solid. ERRORS: holes FreeCAD refuses, in its words.
Plain Python and cad_agent.feature only, so FreeCAD's own Python can import it.
"""
from cad_agent.feature import (ArcOfCircle, Circle, Hole, LineSegment, Pad, Point, Sketch)


def rect(x0, y0, x1, y1):
    return [LineSegment((x0, y0), (x1, y0)), LineSegment((x1, y0), (x1, y1)),
            LineSegment((x1, y1), (x0, y1)), LineSegment((x0, y1), (x0, y0))]


def plate(thick=10.0):
    return [Sketch("Base", "XY", rect(0, 0, 40, 20)), Pad("Pad", "Base", length=thick)]


def top(geometry, z=10.0, name="Holes"):
    """A sketch on the plate's top face (the XY plane moved up), whose normal points out of the material."""
    return Sketch(name, "XY", geometry, attachment_offset=(0, 0, z))


