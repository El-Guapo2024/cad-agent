"""Write cad_agent/fcexpr_data.json, the tables the Python formula engine (cad_agent/fcexpr.py) runs on, from the TypeScript
sources the browser's engine (ui/src/expr.ts) runs on: the LALR tables of FreeCAD's expression grammar (ui/src/expr-grammar.ts,
made by scripts/exprgen.py from App/Expression.y), the units (ui/src/units-data.ts) and the unit schemas (ui/src/units-schemas.ts).
The JSON carries a hash of those sources, so tests/test_fcexpr.py can tell that it is stale.

    python3 ui/scripts/fcexprpy.py            # write the JSON
    python3 ui/scripts/fcexprpy.py --check    # exit 1 if the JSON is not what the sources make

The TS files are generated and hold JavaScript literals (JSON with trailing commas and // comments): each exported constant is
cut out by bracket matching and read as a Python literal.
"""
import argparse
import ast
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
UI = HERE.parent
REPO = UI.parent
OUT = REPO / "cad_agent" / "fcexpr_data.json"
SOURCES = ["src/expr-grammar.ts", "src/units-data.ts", "src/units-schemas.ts"]


def source_hash(ui=UI):
    """A hash of the TS sources the JSON is made of (line ends as in git)."""
    h = hashlib.sha256()
    for name in SOURCES:
        h.update(name.encode() + b"\0" + (Path(ui) / name).read_bytes().replace(b"\r\n", b"\n") + b"\0")
    return h.hexdigest()


def _literal_at(text, start):
    """The JavaScript literal that starts at text[start] (a '[' or '{'), as Python source: comments dropped, true/false/null
    spelled the Python way. Returns (python_source, end)."""
    out = []
    depth = 0
    i = start
    n = len(text)
    while i < n:
        c = text[i]
        if c in "\"'":
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
            continue
        if text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
            continue
        if text.startswith("/*", i):
            i = text.index("*/", i) + 2
            continue
        if c.isalpha() or c == "_":
            j = i
            while j < n and (text[j].isalnum() or text[j] in "_$"):
                j += 1
            word = text[i:j]
            out.append({"true": "True", "false": "False", "null": "None"}.get(word, word))
            i = j
            continue
        if c in "[{":
            depth += 1
        elif c in "]}":
            depth -= 1
            if depth == 0:
                out.append(c)
                return "".join(out), i + 1
        out.append(c)
        i += 1
    raise ValueError("unterminated literal")


def exported(text, name):
    """The value of `export const NAME ... = <literal>` in a TS file."""
    key = f"export const {name}"
    at = text.find(key)
    if at < 0:
        raise KeyError(f"no 'export const {name}'")
    eq = text.index("=", at + len(key))
    start = eq + 1
    while text[start] not in "[{":
        start += 1
    src, _ = _literal_at(text, start)
    return ast.literal_eval(src)


def build(ui=UI):
    ui = Path(ui)
    grammar = (ui / "src/expr-grammar.ts").read_text(encoding="utf-8")
    units = (ui / "src/units-data.ts").read_text(encoding="utf-8")
    schemas = (ui / "src/units-schemas.ts").read_text(encoding="utf-8")
    return {
        "about": "Generated by ui/scripts/fcexprpy.py from ui/src/expr-grammar.ts, units-data.ts and units-schemas.ts (FreeCAD main "
                 "3160daf1e2b6: App/Expression.y, Base/Quantity.l, Base/UnitsConvData.h, Base/UnitsSchemasData.h; LGPL-2.1-or-later). Do not edit.",
        "sources": source_hash(ui),
        "terminals": exported(grammar, "TERMINALS"),
        "nonterminals": exported(grammar, "NONTERMINALS"),
        "rules": exported(grammar, "RULES"),
        "states": exported(grammar, "STATES"),
        "units": exported(units, "UNITS"),
        "unit_types": exported(units, "UNIT_TYPES"),
        "schemas": exported(schemas, "SCHEMAS"),
    }


def render(data):
    return json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="only check that the JSON is current")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()
    text = render(build())
    out = Path(args.out)
    if args.check:
        current = out.exists() and out.read_text(encoding="utf-8") == text
        print(f"fcexprpy: {out} is {'current' if current else 'STALE: run python3 ui/scripts/fcexprpy.py'}")
        return 0 if current else 1
    out.write_text(text, encoding="utf-8")
    print(f"fcexprpy: wrote {out} ({len(text):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
