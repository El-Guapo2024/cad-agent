"""Generates ui/src/draft_props.ts: the property view of each Draft object (cad_agent/feature_draft.py), as FreeCAD 26.3
(3160daf1e2b6) shows a fresh one, made as its draftmake maker makes it. Run it in FreeCAD, from the repository's root:

    $FREECAD/freecadcmd ui/scripts/draftprops.py

The rows are partprops.py's: the properties not Hidden with their group, type, an enumeration's items and ReadOnly; in a
group in DEFAULTS' order, then the rest; Base's Placement and Label last; the groups in name order. The key is the part
file's keyword (null for one it does not hold, shown read-only).
"""
import json
import os
import sys
from pathlib import Path

ROOT = Path(os.getcwd())
sys.path.insert(0, str(ROOT))
import FreeCAD as App  # noqa: E402

from cad_agent import feature_draft as Draft  # noqa: E402
from cad_agent import feature_part as Part  # noqa: E402

SKIP = {"ShapeMaterial", "Visibility", "AttacherType", "Label2", "Label", "Placement", "Shape", "ExpressionEngine",
        "Proxy", "_ElementMapVersion"}
doc = App.newDocument("draftprops")
types = {}
for kind, cls in sorted(Draft.OBJECTS.items()):
    obj = doc.addObject(cls.FC_TYPE, kind.split(".")[1])
    cls.fc_setup(Part.KwFeature.__new__(cls), obj, None)
    keys = {cls.prop_name(k): k for k in cls.DEFAULTS}
    order = [cls.prop_name(k) for k in cls.DEFAULTS if k not in ("label", "placement", "visibility")]
    rows = []
    for p in order + [p for p in obj.PropertiesList if p not in order]:
        if p in SKIP or p not in obj.PropertiesList:
            continue
        mode = obj.getEditorMode(p)
        if "Hidden" in mode:
            continue
        t = obj.getTypeIdOfProperty(p)
        row = {"g": obj.getGroupOfProperty(p) or "Base", "p": p, "k": keys.get(p), "t": t}
        if t == "App::PropertyEnumeration":
            row["e"] = obj.getEnumerationsOfProperty(p)
        if "ReadOnly" in mode:
            row["ro"] = 1
        rows.append(row)
    rows.append({"g": "Base", "p": "Placement", "k": "placement", "t": "App::PropertyPlacement"})
    rows.append({"g": "Base", "p": "Label", "k": "label", "t": "App::PropertyString"})
    groups = sorted({r["g"] for r in rows})
    types[cls.TYPE_ID] = [r for g in groups for r in rows if r["g"] == g]
App.closeDocument(doc.Name)
body = ",\n".join(f" {json.dumps(t)}: [\n" + "".join(f"  {json.dumps(r)},\n" for r in rows) + " ]"
                  for t, rows in types.items())
(ROOT / "ui" / "src" / "draft_props.ts").write_text(
    "// SPDX-License-Identifier: LGPL-2.1-or-later\n"
    "// GENERATED by ui/scripts/draftprops.py from what FreeCAD 26.3 (3160daf1e2b6) shows for each Draft object\n"
    "// (cad_agent/feature_draft.py's kinds, made as draftmake makes them): do not edit. The rows are part_props.ts's.\n"
    "import type { PartProp } from './part_props'\n"
    f"export const DRAFT_PROPS: Record<string, PartProp[]> = {{\n{body},\n}}\n")
print(len(types), "types")
