"""Writes ui/src/draft_cmds.ts: every Draft GUI command's Pixmap, MenuText and ToolTip, and the commands a group command
(Draft_ArcTools, Draft_ArrayTools, ...) offers, read from FreeCAD's draftguitools/*.py (GetResources and Gui.addCommand),
and the workbench's menus and toolbars from draftutils/init_tools.py.

    python3 ui/scripts/draftcmds.py $FREECAD/../Mod/Draft      (FreeCAD 26.3, 3160daf1e2b6)
"""
import ast
import json
import sys
from pathlib import Path

DRAFT = Path(sys.argv[1])


def lit(node, consts):
    """A literal, with QT_TRANSLATE_NOOP("ctx", "text") as its text and names of module strings resolved."""
    if isinstance(node, ast.Call) and getattr(node.func, "id", getattr(node.func, "attr", "")) in (
            "QT_TRANSLATE_NOOP", "translate"):
        return lit(node.args[-1], consts)
    if isinstance(node, ast.Name) and node.id in consts:
        return consts[node.id]
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        a, b = lit(node.left, consts), lit(node.right, consts)
        return a + b if isinstance(a, str) and isinstance(b, str) else None
    if isinstance(node, ast.JoinedStr):
        return None
    try:
        return ast.literal_eval(node)
    except ValueError:
        return None


cmds, groups = {}, {}
for p in sorted((DRAFT / "draftguitools").glob("gui_*.py")):
    tree = ast.parse(p.read_text())
    consts = {n.targets[0].id: n.value.value for n in tree.body if isinstance(n, ast.Assign)
              and isinstance(n.targets[0], ast.Name) and isinstance(n.value, ast.Constant)}
    res = {}
    for c in [n for n in tree.body if isinstance(n, ast.ClassDef)]:
        for f in [n for n in c.body if isinstance(n, ast.FunctionDef)]:
            if f.name == "GetResources":
                for r in ast.walk(f):
                    if isinstance(r, ast.Return) and isinstance(r.value, ast.Dict):
                        res[c.name] = {lit(k, consts): lit(v, consts) for k, v in zip(r.value.keys, r.value.values)}
            if f.name == "GetCommands":
                for r in ast.walk(f):
                    if isinstance(r, ast.Return):
                        v = lit(r.value, consts)
                        if v is None and isinstance(r.value, ast.Call):   # tuple(self.commands)
                            v = None
                        groups[c.name] = v
            if f.name == "__init__":
                for a in ast.walk(f):
                    if isinstance(a, ast.Assign) and any(getattr(t, "attr", "") == "commands" for t in a.targets):
                        groups[c.name] = lit(a.value, consts)
    for n in ast.walk(tree):
        if isinstance(n, ast.Call) and getattr(n.func, "attr", "") == "addCommand" and len(n.args) == 2:
            name = lit(n.args[0], consts)
            cls = getattr(n.args[1].func, "id", None) if isinstance(n.args[1], ast.Call) else None
            if name and cls in res:
                r = res[cls]
                cmds[name] = {"pixmap": r.get("Pixmap"), "menu": r.get("MenuText"), "tip": r.get("ToolTip"),
                              "accel": r.get("Accel")}
                if groups.get(cls):
                    cmds[name]["group"] = list(groups[cls])

it = ast.parse((DRAFT / "draftutils" / "init_tools.py").read_text())
lists = {f.name: ast.literal_eval(r.value) for f in it.body if isinstance(f, ast.FunctionDef)
         for r in ast.walk(f) if isinstance(r, ast.Return) and isinstance(r.value, ast.List)}
out = Path(__file__).resolve().parents[1] / "src" / "draft_cmds.ts"
out.write_text("// SPDX-License-Identifier: LGPL-2.1-or-later\n"
               "// GENERATED by ui/scripts/draftcmds.py from FreeCAD 26.3's (3160daf1e2b6) src/Mod/Draft/draftguitools/*.py\n"
               "// (each command's GetResources) and draftutils/init_tools.py (the workbench's lists): do not edit.\n"
               "export type DraftCmd = { pixmap: string | null; menu: string | null; tip: string | null; accel: string | null; group?: string[] }\n"
               f"export const DRAFT_CMDS: Record<string, DraftCmd> = {json.dumps(cmds, indent=1, ensure_ascii=False)}\n"
               f"export const DRAFT_LISTS: Record<string, string[]> = {json.dumps(lists, indent=1)}\n")
print(len(cmds), "commands;", ", ".join(k for k, v in cmds.items() if v.get("group")))
