#!/usr/bin/env python3
"""Generates ui/src/techdraw_props_more.ts: the property view (Data and View tabs) of the leader line, rich text, symbol, weld
symbol, tile weld, image and clip group, as the real FreeCAD shows it.

    .venv/bin/python ui/scripts/techdrawprops_more.py [ui/src/techdraw_props_more.ts]

The rows and their order are the property view's of the real GUI (ui/scripts/fctechdraw_more.json, props_<type>_<name>: groups and
names), each with FreeCAD's property type and an enumeration's items (tests/golden/techdraw/more_types.json, ui/scripts/
fctechdraw_more_types.py) and the page file's keyword for it (cad_agent/techdraw_objs.py), or null for a property the file does not
hold, which the page shows read-only. The View tab's rows are the view provider's properties the file holds beside the object's.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent))
from cad_agent import techdraw as T  # noqa: E402

TYPE_OF = {"DrawLeaderLine": "TechDraw::DrawLeaderLine", "DrawRichAnno": "TechDraw::DrawRichAnno", "DrawViewSymbol": "TechDraw::DrawViewSymbol",
           "DrawWeldSymbol": "TechDraw::DrawWeldSymbol", "DrawTileWeld": "TechDraw::DrawTileWeld", "DrawViewImage": "TechDraw::DrawViewImage",
           "DrawViewClip": "TechDraw::DrawViewClip"}
VIEW_KEYS = {"DrawLeaderLine": {"Color": ("color", "App::PropertyColor"), "Line Width": ("line_width", "App::PropertyFloat"),
                                "Line Style": ("line_style", "App::PropertyEnumeration"), "Use Old Coords": ("use_old_coords", "App::PropertyBool")},
             "DrawRichAnno": {"Line Color": ("line_color", "App::PropertyColor"), "Line Width": ("line_width", "App::PropertyFloat"),
                              "Line Style": ("line_style", "App::PropertyEnumeration")},
             "DrawWeldSymbol": {"Font": ("font", "App::PropertyString"), "Font Size": ("font_size", "App::PropertyLength"),
                                "Tile Font Size": ("tile_font_size", "App::PropertyLength")},
             "DrawViewSymbol": {"Stack Order": ("stack_order", "App::PropertyInteger"), "Legacy Scaling": ("legacy_scaling", "App::PropertyBool")},
             "DrawViewImage": {"Crop": ("crop", "App::PropertyBool")}, "DrawViewClip": {"Clip Children": ("clip_children", "App::PropertyBool")}}
REC = {"DrawLeaderLine": "props_DrawLeaderLine_", "DrawRichAnno": "props_DrawRichAnno_", "DrawViewSymbol": "props_DrawViewSymbol_",
       "DrawWeldSymbol": "props_DrawWeldSymbol_", "DrawTileWeld": "props_DrawTileWeld_", "DrawViewImage": "props_DrawViewImage_",
       "DrawViewClip": "props_DrawViewClip_"}


def shown(name: str) -> str:
    return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", name)


def main():
    dst = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "src" / "techdraw_props_more.ts"
    rec = json.loads((HERE / "fctechdraw_more.json").read_text())
    types = json.loads((HERE.parent.parent / "tests" / "golden" / "techdraw" / "more_types.json").read_text())
    data, view = {}, {}
    for kind, tid in TYPE_OF.items():
        cls = T.CLASSES[kind]
        props = types[tid]
        by_shown = {shown(p): p for p in props}
        keys = {cls.prop_name(k): k for k in cls.DEFAULTS}
        key = next((k for k in rec if k.startswith(REC[kind])), None)
        if key is None:
            continue
        for tab, out in (("data", data), ("view", view)):
            rows, group = [], None
            for r in (rec[key][tab][0] if rec[key][tab] else []):
                if r["depth"] == 0:
                    group = r["name"]
                    continue
                if tab == "data":
                    p = by_shown.get(r["name"], r["name"].replace(" ", ""))
                    x = props.get(p, {})
                    rows.append({"g": group, "p": r["name"], "k": keys.get(p) if p not in ("Leader",) or True else None, "t": x.get("type", ""),
                                 **({"e": x["enum"]} if x.get("enum") else {})})
                else:
                    k, t = VIEW_KEYS.get(kind, {}).get(r["name"], (None, ""))
                    rows.append({"g": group, "p": r["name"], "k": k, "t": t})
            out[kind] = rows
    for kind in data:                                  # a property the file holds only through a list keeps no key (Views, EditableTexts ...)
        for r in data[kind]:
            if r["p"] in ("Editable Texts", "Symbol Included", "Image Included", "Rotation Vector", "Caption Location", "Tile Column") or r["t"] in (
                    "App::PropertyFileIncluded", "App::PropertyVectorList"):
                r["k"] = None if r["p"] != "Way Points" else r["k"]
    head = ("// SPDX-License-Identifier: LGPL-2.1-or-later\n// GENERATED by ui/scripts/techdrawprops_more.py from what the real FreeCAD 26.3 (3160daf1e2b6) shows for each of these object types\n"
            "// (ui/scripts/fctechdraw_more.json, fctechdraw_more_types.py): do not edit. Per type, the property view's rows: group, the name FreeCAD shows,\n"
            "// the page file's keyword for it (null: shown, not held), FreeCAD's property type, an enumeration's items.\n"
            "import type { TdProp } from './techdraw_props'\n\n")
    body = "export const TD_PROPS_MORE: Record<string, TdProp[]> = " + json.dumps(data, indent=1, ensure_ascii=False) + "\n\n"
    body += "export const TD_VIEW_PROPS_MORE: Record<string, TdProp[]> = " + json.dumps(view, indent=1, ensure_ascii=False) + "\n"
    dst.write_text(head + body)
    print(f"techdrawprops_more: {len(data)} types -> {dst}")


if __name__ == "__main__":
    main()
