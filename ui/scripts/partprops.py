#!/usr/bin/env python3
"""Generates ui/src/part_props.ts: each Part object type's property view, as the real FreeCAD shows it.

    python3 ui/scripts/fcpart.py OUT_DIR                      # the real FreeCAD, once (OUT_DIR/fcpart.json)
    .venv/bin/python ui/scripts/partprops.py OUT_DIR/fcpart.json [ui/src/part_props.ts]

For each type, the properties FreeCAD's property view lists (not Hidden) with their group, FreeCAD's property type and an
enumeration's items, from the objects fcpart_dump.py made in FreeCAD; in each group in the order the type declares them
(cad_agent/feature_part*.py's DEFAULTS, ported in FreeCAD's ADD_PROPERTY order), Base's Placement and Label last, as
PropertyEditor lists them; the groups in name order. The key is the part file's keyword for the property (null for one
the part file does not hold, which the page shows read-only). The generated file is not edited by hand.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent))
from cad_agent import feature_part as Part  # noqa: E402

PROXY = {"TubeFeature": "Part::Tube", "FeatureBooleanFragments": "Part::BooleanFragments", "FeatureXOR": "Part::XOR",
         "FeatureConnect": "Part::Connect", "FeatureSlice": "Part::Slice", "_CompoundFilter": "Part::CompoundFilter",
         "FeatureEmbed": "Part::Embed", "FeatureCutout": "Part::Cutout", "FeatureToleranceSet": "Part::ToleranceSet"}
SKIP = {"ShapeMaterial", "Visibility", "AttacherType", "Label2"}


def collect(dump):
    """{TypeId: props_of() of a fresh-made object} from every object fcpart_dump.py recorded."""
    out = dict(dump.get("types", {}))
    groups = [v for k, v in dump.items() if k.startswith("cmd_") and isinstance(v, dict)]
    for g in groups:
        for o in g.get("made", []):
            tid = PROXY.get(o.get("proxy"), o["type"])
            if o["name"] in g.get("props", {}) and tid not in out:
                out[tid] = g["props"][o["name"]]
    for made in dump.get("primitives", {}).get("made", {}).values():
        for o in made:
            out.setdefault(o["type"], o["props"])
    return out


def main():
    # fcpart.json, then any more dumps (fcpart_static.json), then the .ts to write
    dumps = [Path(a) for a in sys.argv[1:] if a.endswith(".json")]
    ts = [Path(a) for a in sys.argv[1:] if a.endswith(".ts")]
    dst = ts[0] if ts else HERE.parent / "src" / "part_props.ts"
    fc = {}
    for path in dumps:
        for tid, props in collect(json.loads(path.read_text())).items():
            fc.setdefault(tid, props)
    types = {}
    for kind, cls in sorted(Part.OBJECTS.items()):
        props = fc.get(cls.TYPE_ID) or fc.get(getattr(cls, "FC_TYPE", None))      # a recipe's object is a Part::Feature
        if props is None:
            print(f"partprops: FreeCAD made no {cls.TYPE_ID}; its view is its DEFAULTS")
            props = {}
        keys = {cls.prop_name(k): k for k in cls.DEFAULTS}
        order = [cls.prop_name(k) for k in cls.DEFAULTS if k not in ("label", "placement", "visibility")]
        rows = []
        for p in order + [p for p in props if p not in order]:
            x = props.get(p)
            if p in SKIP or (x is not None and "Hidden" in x.get("mode", [])) or p in ("Label", "Placement"):
                continue
            if x is None:
                continue                   # not a property FreeCAD's object has (test_defaults_are_freecads says so)
            row = {"g": x["group"] or "Base", "p": p, "k": keys.get(p), "t": x["type"]}
            if x.get("enums"):
                row["e"] = x["enums"]
            if "ReadOnly" in x.get("mode", []):
                row["ro"] = 1
            rows.append(row)
        if "Placement" in props:
            rows.append({"g": "Base", "p": "Placement", "k": "placement" if "placement" in cls.DEFAULTS else None,
                         "t": "App::PropertyPlacement"})
        rows.append({"g": "Base", "p": "Label", "k": "label", "t": "App::PropertyString"})
        groups = sorted({r["g"] for r in rows})
        types[cls.TYPE_ID] = [r for g in groups for r in rows if r["g"] == g]
    head = """// SPDX-License-Identifier: LGPL-2.1-or-later
// GENERATED by ui/scripts/partprops.py from what the real FreeCAD 26.3 (3160daf1e2b6) shows for each Part object type
// (ui/scripts/fcpart.json): do not edit. Per type, the property view's rows: group, FreeCAD's property name, the part file's
// keyword (null: shown, not held), the property type, an enumeration's items, ro for a read-only one.
export type PartProp = { g: string; p: string; k: string | null; t: string; e?: string[]; ro?: 1 }
export const PART_PROPS: Record<string, PartProp[]> = """
    body = "{\n" + "".join(f" {json.dumps(t)}: [\n" + "".join(f"  {json.dumps(r, ensure_ascii=False)},\n" for r in rows) + " ],\n"
                           for t, rows in types.items()) + "}\n"
    dst.write_text(head + body)
    print(f"partprops: {len(types)} types -> {dst}")


main()
