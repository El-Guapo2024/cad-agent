"""Makes ui/src/expr-grammar.ts from FreeCAD's Expression.y: the parser's tables, built as GNU Bison builds them.

    python3 scripts/exprgen.py Expression.y > src/expr-grammar.ts

Expression.y is src/App/Expression.y of FreeCAD main 3160daf1e2b6 (the commit PARITY.md ports). The tables are the LALR(1)
automaton of its grammar, with Bison's conflict rules: a shift/reduce conflict is settled by precedence when both the
rule (its %prec, else its last terminal) and the lookahead token have one (the higher wins; at the same level %left
reduces and %right shifts), otherwise it is a shift; a reduce/reduce conflict is the rule that comes first. As Bison
does, each state's most common reduction is its default, taken for every token that has no action of its own, and a
state with nothing else to do reduces without reading the next token. expr.ts runs the tables and holds the semantic
actions, which it finds by the text of each rule (this prints it with the rule), so a regenerated grammar that changes
a rule makes it fail loudly, not quietly.
"""
import json
import re
import sys
from collections import defaultdict

HEADER = """// SPDX-License-Identifier: LGPL-2.1-or-later
// Follows FreeCAD (https://github.com/FreeCAD/FreeCAD, commit 3160daf1e2b6), copyright of the files below (each is
// LGPL-2.0-or-later or LGPL-2.1-or-later as it states; ui/NOTICE has them all):
//   src/App/Expression.y: 2010 Jürgen Riegel; 2015 Eivind Kvedalen
// The LALR(1) tables of FreeCAD's expression grammar (src/App/Expression.y at FreeCAD main 3160daf1e2b6, LGPL-2.1-or-later),
// built the way GNU Bison builds them: its precedence rules for shift/reduce conflicts, the first rule for reduce/reduce
// ones, each state's most common reduction as its default (taken for any token without an action of its own, and without
// reading the next token when it is all the state has). Generated by scripts/exprgen.py; do not edit.
"""


def strip_comments(text):
    out, i, n = [], 0, len(text)
    while i < n:
        if text.startswith("/*", i):
            j = text.index("*/", i + 2)
            out.append(" ")
            i = j + 2
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text[i] == "'":
            j = i + 1
            while text[j] != "'":
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text[i] == '"':
            j = i + 1
            while text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def skip_braces(text, i):
    """text[i] == '{': the index after the matching '}' (strings and character literals skipped)."""
    depth, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        elif c in "\"'":
            j = i + 1
            while text[j] != c:
                j += 2 if text[j] == "\\" else 1
            i = j
        i += 1
    raise ValueError("unbalanced braces")


def parse_y(path):
    src = open(path, encoding="utf-8").read()
    # drop the %{ ... %} prologue and the comments, then split into declarations and rules at %%
    src = re.sub(r"%\{.*?%\}", " ", src, flags=re.S)
    src = strip_comments(src)
    decl, rules, *_ = src.split("%%")
    prec = {}          # token -> (level, assoc)
    level = 0
    tokens = []        # in order of appearance
    start = None
    for line in decl.split("\n"):
        line = line.strip()
        m = re.match(r"%(token|left|right|nonassoc|precedence)\b(.*)", line)
        if m:
            kind, rest = m.groups()
            rest = re.sub(r"<[^>]*>", " ", rest)
            names = re.findall(r"'(?:\\.|[^'\\])'|[A-Za-z_][A-Za-z0-9_]*", rest)
            if kind != "token":
                level += 1
            for t in names:
                if t not in tokens:
                    tokens.append(t)
                if kind != "token":
                    prec[t] = (level, kind)
        m = re.match(r"%start\s+(\w+)", line)
        if m:
            start = m.group(1)
    # the rules: name ':' alternatives separated by '|', ended by ';'
    pos, productions, nonterms = 0, [], []
    n = len(rules)
    while True:
        while pos < n and rules[pos].isspace():
            pos += 1
        if pos >= n:
            break
        m = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*:").match(rules, pos)
        if not m:
            raise ValueError("rule expected at " + rules[pos:pos + 40])
        lhs = m.group(1)
        if lhs not in nonterms:
            nonterms.append(lhs)
        pos = m.end()
        while True:
            rhs, pr = [], None
            while pos < n:
                if rules[pos].isspace():
                    pos += 1
                elif rules[pos] == "{":
                    pos = skip_braces(rules, pos)
                elif rules.startswith("%prec", pos):
                    m2 = re.compile(r"%prec\s+([A-Za-z_][A-Za-z0-9_]*)").match(rules, pos)
                    pr = m2.group(1)
                    pos = m2.end()
                elif rules[pos] == "'":
                    j = pos + 1
                    while rules[j] != "'":
                        j += 2 if rules[j] == "\\" else 1
                    rhs.append(rules[pos:j + 1])
                    pos = j + 1
                elif rules[pos] in "|;":
                    break
                elif re.compile(r"[A-Za-z_][A-Za-z0-9_]*\s*:").match(rules, pos):
                    break              # the next rule starts here: Bison lets the ';' before it be left out
                else:
                    m2 = re.compile(r"[A-Za-z_][A-Za-z0-9_]*").match(rules, pos)
                    if not m2:
                        raise ValueError("bad rule text at " + rules[pos:pos + 40])
                    rhs.append(m2.group(0))
                    pos = m2.end()
            productions.append((lhs, rhs, pr))
            if pos < n and rules[pos] == "|":
                pos += 1
                continue
            if pos < n and rules[pos] == ";":
                pos += 1
            break
    return tokens, prec, nonterms, productions, start or productions[0][0]


class Grammar:
    def __init__(self, tokens, prec, nonterms, productions, start):
        self.terms = ["$end"] + [t for t in tokens if t not in nonterms]
        for _, rhs, _ in productions:
            for s in rhs:
                if s not in nonterms and s not in self.terms:
                    self.terms.append(s)          # character tokens such as '+' that are not declared
        self.nonterms = ["$accept"] + nonterms
        self.rules = [("$accept", [start, "$end"], None)] + productions
        self.prec = prec
        self.is_term = set(self.terms)
        # a rule's precedence: its %prec, else its last terminal
        self.rule_prec = []
        for lhs, rhs, pr in self.rules:
            if pr is not None:
                self.rule_prec.append(prec.get(pr, (0, None)))
            else:
                last = next((s for s in reversed(rhs) if s in self.is_term), None)
                self.rule_prec.append(prec.get(last, (0, None)) if last else (0, None))
        self.by_lhs = defaultdict(list)
        for i, (lhs, _, _) in enumerate(self.rules):
            self.by_lhs[lhs].append(i)
        self.first = self.compute_first()

    def compute_first(self):
        first = {s: {s} for s in self.terms}
        nullable = set()
        for s in self.nonterms:
            first[s] = set()
        changed = True
        while changed:
            changed = False
            for lhs, rhs, _ in self.rules:
                all_null = True
                for s in rhs:
                    add = first[s] - first[lhs]
                    if add:
                        first[lhs] |= add
                        changed = True
                    if s not in nullable:
                        all_null = False
                        break
                if all_null and lhs not in nullable:
                    nullable.add(lhs)
                    changed = True
        self.nullable = nullable
        return first

    def first_of(self, seq, la):
        out = set()
        for s in seq:
            out |= self.first[s]
            if s not in self.nullable:
                return out
        return out | la

    def closure(self, items):
        """items: {(rule, dot): set(lookahead)} -> the same with the closure added."""
        items = {k: set(v) for k, v in items.items()}
        work = list(items)
        while work:
            r, d = work.pop()
            rhs = self.rules[r][1]
            if d >= len(rhs) or rhs[d] in self.is_term:
                continue
            la = self.first_of(rhs[d + 1:], items[(r, d)])
            for r2 in self.by_lhs[rhs[d]]:
                key = (r2, 0)
                cur = items.setdefault(key, set())
                if not la <= cur:
                    cur |= la
                    work.append(key)
        return items

    def build(self):
        states, by_core, trans = [], {}, []
        def add(kernel):
            core = frozenset(kernel)
            if core in by_core:
                sid = by_core[core]
                changed = False
                for k, la in kernel.items():
                    if not la <= states[sid][k]:
                        states[sid][k] |= la
                        changed = True
                return sid, changed
            sid = len(states)
            by_core[core] = sid
            states.append({k: set(v) for k, v in kernel.items()})
            trans.append({})
            return sid, True
        add({(0, 0): {"$end"}})
        queue = [0]
        while queue:
            sid = queue.pop(0)
            items = self.closure(states[sid])
            moves = defaultdict(dict)
            for (r, d), la in items.items():
                rhs = self.rules[r][1]
                if d < len(rhs):
                    moves[rhs[d]][(r, d + 1)] = la
            for sym in sorted(moves, key=lambda s: (s not in self.is_term, self.terms.index(s) if s in self.is_term else self.nonterms.index(s))):
                tid, changed = add(moves[sym])
                trans[sid][sym] = tid
                if changed and tid not in queue:
                    queue.append(tid)
        return states, trans

    def tables(self):
        states, trans = self.build()
        rows = []
        conflicts = {"sr": 0, "rr": 0, "resolved": 0}
        for sid, kernel in enumerate(states):
            items = self.closure(kernel)
            shifts = {t: trans[sid][t] for t in trans[sid] if t in self.is_term}
            gotos = {t: trans[sid][t] for t in trans[sid] if t not in self.is_term}
            reds = {}                                   # rule -> set of lookahead tokens
            for (r, d), la in items.items():
                if d == len(self.rules[r][1]) and r != 0:
                    reds[r] = set(la)
            ordered = sorted(reds)
            # precedence settles shift/reduce conflicts
            for r in ordered:
                lvl, _ = self.rule_prec[r]
                if not lvl:
                    continue
                for t in sorted(reds[r] & set(shifts)):
                    tl, assoc = self.prec.get(t, (0, None))
                    if not tl:
                        continue
                    conflicts["resolved"] += 1
                    if tl < lvl:
                        del shifts[t]
                    elif tl > lvl:
                        reds[r].discard(t)
                    elif assoc == "left":
                        del shifts[t]
                    elif assoc == "right":
                        reds[r].discard(t)
                    elif assoc == "nonassoc":
                        del shifts[t]
                        reds[r].discard(t)
                    else:
                        raise ValueError(f"state {sid}: no associativity to settle {t} against rule {r}")
            # what is left: reduce/reduce goes to the first rule, shift/reduce to the shift
            act = {}
            for r in reversed(ordered):
                for t in reds[r]:
                    if t in act and act[t][0] == "r" and act[t][1] != r:
                        conflicts["rr"] += 1
                    act[t] = ("r", r)
            for t, s in shifts.items():
                if t in act:
                    conflicts["sr"] += 1
                act[t] = ("s", s)
            # the default reduction: the reduction most tokens ask for (the first on a tie)
            consistent = len(ordered) == 1 and not shifts and not gotos
            default = -1
            if ordered:
                if consistent:
                    default = ordered[0]
                else:
                    best = 0
                    for r in ordered:
                        count = sum(1 for a in act.values() if a == ("r", r))
                        if count > best:
                            best, default = count, r
            explicit_reds = {t: a[1] for t, a in act.items() if a[0] == "r" and a[1] != default}
            explicit_shifts = {t: (-1 if states[a[1]] == {(0, 2): {"$end"}} else a[1]) for t, a in act.items() if a[0] == "s"}   # -1: the input is complete
            rows.append({"shift": explicit_shifts, "reduce": explicit_reds, "default": default, "goto": gotos,
                         "token": bool(explicit_shifts or explicit_reds or default < 0)})
        return rows, conflicts

    def rule_text(self, i):
        lhs, rhs, pr = self.rules[i]
        return f"{lhs}: {' '.join(rhs) if rhs else '%empty'}" + (f" %prec {pr}" if pr else "")


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__)
    g = Grammar(*parse_y(argv[1]))
    rows, conflicts = g.tables()
    ti = {t: i for i, t in enumerate(g.terms)}
    ni = {t: i for i, t in enumerate(g.nonterms)}
    out = [HEADER]
    out.append(f"// {len(rows)} states, {len(g.rules)} rules; conflicts settled by precedence {conflicts['resolved']}, left to shift {conflicts['sr']}, left to the first rule {conflicts['rr']}.")
    out.append("export const TERMINALS = " + json.dumps(g.terms, ensure_ascii=False))
    out.append("export const NONTERMINALS = " + json.dumps(g.nonterms))
    out.append("/** [left-hand side (index into NONTERMINALS), number of symbols on the right, the rule's text] */")
    out.append("export const RULES: [number, number, string][] = [")
    for i, (lhs, rhs, pr) in enumerate(g.rules):
        out.append(f"  [{ni[lhs]}, {len(rhs)}, {json.dumps(g.rule_text(i), ensure_ascii=False)}],")
    out.append("]")
    out.append("/** Per state: [shifts [token, state, ...], reductions [token, rule, ...], default rule or -1, gotos [nonterminal, state, ...], whether it reads the next token]. */")
    out.append("export const STATES: [number[], number[], number, number[], number][] = [")
    for r in rows:
        sh = [x for t, s in sorted(r["shift"].items(), key=lambda kv: ti[kv[0]]) for x in (ti[t], s)]
        rd = [x for t, s in sorted(r["reduce"].items(), key=lambda kv: ti[kv[0]]) for x in (ti[t], s)]
        gt = [x for t, s in sorted(r["goto"].items(), key=lambda kv: ni[kv[0]]) for x in (ni[t], s)]
        out.append(f"  [{json.dumps(sh)}, {json.dumps(rd)}, {r['default']}, {json.dumps(gt)}, {1 if r['token'] else 0}],")
    out.append("]")
    print("\n".join(out))
    print(f"exprgen: {len(rows)} states, {len(g.rules)} rules, {conflicts}", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv)
