#!/usr/bin/env python3
"""Generates ui/src/techdraw_props.ts: each TechDraw object type's property view (Data tab), as the real FreeCAD shows it.

    OUT=TYPES.json $FREECAD/freecadcmd ui/scripts/fctechdraw_types.py      # each type's properties in a fresh profile
    .venv/bin/python ui/scripts/techdrawprops.py TYPES.json [ui/src/techdraw_props.ts]

The rows and their order are the property view's of the real GUI (ui/scripts/fctechdraw.json, props_<object>: groups and
names, PropertyItem's names with a space before each capital after a small letter); a type the recording has no view of
(DrawViewBalloon) takes its visible properties from TYPES.json, grouped, the groups in name order. Each row says FreeCAD's
property type and an enumeration's items (TYPES.json), and the page file's keyword for it (cad_agent/techdraw.py), or
null for a property the page file does not hold, which the page shows read-only. The generated file is not edited by hand.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent))
from cad_agent import techdraw as T  # noqa: E402

REC = {"DrawPage": "props_Page", "DrawSVGTemplate": "props_Template", "DrawProjGroupItem": "props_View",
       "DrawViewPart": "props_View", "DrawProjGroup": "props_ProjGroup", "DrawViewSection": "props_SectionView",
       "DrawViewDimension": "props_Dimension", "DrawViewAnnotation": "props_Annotation"}
TYPE_OF = {"DrawPage": "TechDraw::DrawPage", "DrawSVGTemplate": "TechDraw::DrawSVGTemplate",
           "DrawProjGroupItem": "TechDraw::DrawProjGroupItem", "DrawViewPart": "TechDraw::DrawProjGroupItem",
           "DrawProjGroup": "TechDraw::DrawProjGroup", "DrawViewSection": "TechDraw::DrawViewSection",
           "DrawViewDimension": "TechDraw::DrawViewDimension", "DrawViewBalloon": "TechDraw::DrawViewBalloon",
           "DrawViewAnnotation": "TechDraw::DrawViewAnnotation"}


def shown(name: str) -> str:
    """PropertyItem::setPropertyName: a space before a capital that follows a small letter."""
    return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", name)


def main():
    types = json.loads(Path(sys.argv[1]).read_text())
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE.parent / "src" / "techdraw_props.ts"
    rec = json.loads((HERE / "fctechdraw.json").read_text())
    out = {}
    for kind, cls in T.CLASSES.items():
        props = types[TYPE_OF[kind]]
        by_shown = {shown(p): p for p in props}
        keys = {cls.prop_name(k): k for k in cls.DEFAULTS}
        if "type" in cls.DEFAULTS:
            keys["Type"] = "dim_type" if kind == "DrawViewDimension" else "item_type"
        rows = []
        if kind in REC:
            data = rec[REC[kind]]["data"]
            data = data[0] if data and isinstance(data[0], list) else data
            group = None
            for r in data:
                if r["depth"] == 0:
                    group = r["name"]
                    continue
                p = by_shown.get(r["name"], r["name"].replace(" ", ""))
                if kind == "DrawViewPart" and p in ("Type", "RotationVector"):
                    continue
                x = props.get(p, {})
                rows.append({"g": group, "p": r["name"], "k": keys.get(p), "t": x.get("type", ""), **({"e": x["enum"]} if x.get("enum") else {})})
        else:
            for p, x in props.items():
                if "Hidden" in x.get("mode", []) or p in ("Label2", "Visibility", "ExpressionEngine"):
                    continue
                rows.append({"g": x.get("group") or "Base", "p": shown(p), "k": keys.get(p), "t": x.get("type", ""),
                             **({"e": x["enum"]} if x.get("enum") else {})})
            rows.sort(key=lambda r: r["g"])
        out[kind] = rows
    body = ",\n".join(f" {json.dumps(k)}: [\n" + ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows) + "\n ]"
                      for k, rows in out.items())
    dst.write_text(f"""// SPDX-License-Identifier: LGPL-2.1-or-later
// GENERATED by ui/scripts/techdrawprops.py from what the real FreeCAD 26.3 (3160daf1e2b6) shows for each TechDraw object type
// (ui/scripts/fctechdraw.json, fctechdraw_types.py): do not edit. Per type, the property view's rows: group, the name FreeCAD
// shows, the page file's keyword (null: shown, not held), FreeCAD's property type, an enumeration's items.
export type TdProp = {{ g: string; p: string; k: string | null; t: string; e?: string[] }}
export const TD_PROPS: Record<string, TdProp[]> = {{
{body},
}}
""")
    print(f"techdrawprops: {len(out)} types -> {dst}")


if __name__ == "__main__":
    main()
